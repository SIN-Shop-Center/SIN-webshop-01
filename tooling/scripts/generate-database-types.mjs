#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { spawnSync } from 'node:child_process'

const root = process.cwd()
const migrationsDir = resolve(root, 'platform/infra/supabase/migrations')
const outputPath = resolve(root, 'src/types/database.generated.ts')
const checkOnly = process.argv.includes('--check')

const migrationFiles = readdirSync(migrationsDir)
  .filter((name) => name.endsWith('.sql'))
  .sort()

const fingerprint = createHash('sha256')
for (const file of migrationFiles) {
  fingerprint.update(file)
  fingerprint.update('\0')
  fingerprint.update(readFileSync(resolve(migrationsDir, file)))
  fingerprint.update('\0')
}

const schemaFingerprint = fingerprint.digest('hex')
const header = `// Schema fingerprint: sha256:${schemaFingerprint}\n// Generated by pnpm db:types:generate. Do not edit manually.\n\n`

if (checkOnly) {
  const current = readFileSync(outputPath, 'utf8')
  if (!current.startsWith(header)) {
    console.error('Generated database types are stale. Run pnpm db:local:start && pnpm db:types:generate.')
    process.exit(1)
  }
  console.log(`Database type fingerprint matches ${migrationFiles.length} migrations.`)
  process.exit(0)
}

const generated = spawnSync(
  'pnpm',
  [
    'exec',
    'supabase',
    'gen',
    'types',
    'typescript',
    '--local',
    '--workdir',
    'platform/infra',
    '--schema',
    'shop,public',
  ],
  { cwd: root, encoding: 'utf8' },
)

if (generated.status !== 0) {
  process.stderr.write(generated.stderr)
  process.exit(generated.status ?? 1)
}

writeFileSync(outputPath, header + generated.stdout)
console.log(`Generated ${outputPath} from ${migrationFiles.length} local migrations.`)
